"""Write NN.argument.json per paragraph and Argument.lean for an essay (or paper) from its argument.py.
usage: argument_gen.py <dir> <Namespace> [--theorems gaps.json]
(A public copy of stories/private-papers/tools/argument_gen.py, namespace Essays.)"""
import json, os, re, sys, runpy
d, ns = sys.argv[1], sys.argv[2]
A = runpy.run_path(os.path.join(d, 'argument.py'))
P, LORE, EXC = A['P'], A['LORE'], A['EXCERPT']
terms = []
def add(t):
    if t not in terms: terms.append(t)
for t in LORE: add(t)
RULES = A.get('LORE_RULES', [])
for body, head in RULES:
    for t in body + [head]: add(t)
def norm(m):
    extra = {}
    if isinstance(m[-1], dict): extra, m = m[-1], m[:-1]
    d = norm0(m); d.update(extra); return d
def norm0(m):
    k = m[0]
    if k == 'heading': return {'move': k, 'sec': m[1]}
    if k == 'contrast': return {'move': k, 'a': m[1], 'b': m[2], 'uses': m[3]}
    if k in ('promise', 'contribute', 'hedge'): return {'move': k, 't': m[1], 'sec': m[2], 'uses': m[3]}
    if k == 'infer': return {'move': k, 't': m[1], 'premises': m[2], 'uses': m[3]}
    return {'move': k, 't': m[1], 'uses': m[2]}
for n, ms in P.items():
    ms = [norm(m) for m in ms]
    for m in ms:
        for key in ('t', 'a', 'b'):
            if key in m: add(m[key])
        for u in m.get('uses', []) + m.get('premises', []): add(u)
    json.dump({'moves': ms}, open(os.path.join(d, 'paragraphs', f'{n:02d}.argument.json'), 'w'), indent=1)
def T(t): return f'Tm.{t}'
def L(us): return '[' + ', '.join(T(u) for u in us) + ']'
def lean(m):
    k = m['move']
    if k == 'heading': return f'Move.heading {m["sec"]}'
    if k == 'contrast': return f'Move.contrast {T(m["a"])} {T(m["b"])} {L(m["uses"])}'
    if k in ('promise', 'contribute', 'hedge'): return f'Move.{k} {T(m["t"])} {m["sec"]} {L(m["uses"])}'
    if k == 'infer': return f'Move.infer {T(m["t"])} {L(m["premises"])} {L(m["uses"])}'
    name = '«example»' if k == 'example' else k
    return f'Move.{name} {T(m["t"])} {L(m["uses"])}'
out = [f'import LangLib.World.Argument\n\n/-! {ns}: the argument of the excerpt, read paragraph by paragraph\n(generated by tools/essay/argument_gen.py from argument.py). -/\n',
       f'namespace Essays.{ns}\nopen LangLib.World LangLib.World.Argument\n',
       'inductive Tm\n' + ''.join(f'  | {t}\n' for t in terms) + '  deriving DecidableEq, Repr\n',
       f'def lore : List Tm := {L(LORE)}\n',
       '/-- What the reader would infer: objections they would raise unprompted. -/\n'
       'instance : Lore (AFact Tm) := ⟨[' + ', '.join(
         '{ body := [' + ', '.join(f'(AFact.holds {T(b)}, true)' for b in body) + f'], head := (AFact.holds {T(head)}, true) }}'
         for body, head in RULES) + ']⟩\n', f'def w0 : AW Tm := start lore {EXC}\n']
for n, ms in P.items():
    body = ',\n   '.join(lean(norm(m)) for m in ms)
    out.append(f'def p{n:02d} : List (Move Tm) :=\n  [{body}]\n')
out.append('def moves : List (Move Tm) := ' + ' ++ '.join(f'p{n:02d}' for n in P) + '\n')
th = sys.argv[4] if len(sys.argv) > 4 and sys.argv[3] == '--theorems' else None
if th:
    g = json.load(open(th))
    out.append('/-- No term is used before it is lore, defined or promised; promises point forward; deliveries pay off. -/\n'
               'theorem valid : Valid w0 moves := by decide +kernel\n')
    def gap(x):
        m = re.match(r'claim (\w+) is unsupported', x) or None
        if m: return f'Gap.unsupported {T(m.group(1))}'
        m = re.match(r'promise of (\w+) \(section (\d+)\)', x)
        if m: return f'Gap.unpaid {T(m.group(1))} {m.group(2)}'
        m = re.match(r'contribution (\w+) was never', x)
        return f'Gap.unmotivated {T(m.group(1))}'
    out.append('/-- What the excerpt leaves unpaid. -/\ntheorem gaps_are : gapsOf (run w0 moves) =\n    [' + ',\n     '.join(gap(x) for x in g['gaps']) + '] := by decide +kernel\n')
    if not g['gaps']:
        out.append('theorem coherent : Coherent w0 moves := by decide +kernel\n')
    out.append('/-- Denials of what nobody put forward: the excerpt\'s antitheses. -/\ntheorem antitheses_are : antitheses (run w0 moves) = ' + L(g['antitheses']) + ' := by decide +kernel\n')
    out.append('/-- Denials of what was put forward: contrasts. -/\ntheorem contrasts_are : contrasts (run w0 moves) = ' + L(g['contrasts']) + ' := by decide +kernel\n')
    out.append('/-- Promises and contributions left for the rest of the paper. -/\ntheorem deferred_are : deferredList (run w0 moves) =\n    ['
               + ', '.join(f'({T(t)}, {s})' for t, s in g['deferred']) + '] := by decide +kernel\n')
    for t in A.get('LORE_PROBE', []):
        out.append(f'/-- Without {t} in the reader\'s background, a term is used before it is defined. -/\n'
                   f'theorem lore_needed_{t} : ¬ Valid (start (lore.erase {T(t)}) {EXC}) moves := by decide +kernel\n')
else:
    for t in A.get('LORE_PROBE', []):
        out.append(f'#eval (firstFailure (start (lore.erase {T(t)}) {EXC}) moves 0)\n')
    out.append('#eval ((antitheses (run w0 moves)).map short, (contrasts (run w0 moves)).map short)\n')
    out.append('#eval (firstFailure w0 moves 0)\n#eval gaps (run w0 moves)\n#eval (deferredList (run w0 moves)).map fun (t, s) => (short t, s)\n')
out.append(f'end Essays.{ns}\n')
open(os.path.join(d, 'Argument.lean'), 'w').write('\n'.join(out))
print(len(terms), 'terms;', sum(len(v) for v in P.values()), 'moves')
